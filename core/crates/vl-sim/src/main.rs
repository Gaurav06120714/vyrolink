//! `cargo run -p vl-sim --release > ../research/22-routing-simulation-results.md`
//! Prints a reproducible Markdown report comparing routing algorithms.

use vl_routing::Algorithm;
use vl_sim::{Metrics, run, standard_scenarios};

const SEEDS: [u64; 5] = [1, 2, 3, 4, 5];

fn algorithms() -> Vec<(&'static str, Algorithm)> {
    vec![
        ("direct", Algorithm::Direct),
        ("spray L=2", Algorithm::SprayAndWait { initial: 2 }),
        ("spray L=4", Algorithm::SprayAndWait { initial: 4 }),
        ("spray L=8", Algorithm::SprayAndWait { initial: 8 }),
        ("epidemic", Algorithm::Epidemic),
    ]
}

fn mean(ms: &[Metrics], f: impl Fn(&Metrics) -> f64) -> f64 {
    let v: Vec<f64> = ms.iter().map(f).filter(|x| x.is_finite()).collect();
    if v.is_empty() {
        f64::NAN
    } else {
        v.iter().sum::<f64>() / v.len() as f64
    }
}

fn fmt(x: f64, digits: usize) -> String {
    if x.is_finite() {
        format!("{x:.digits$}")
    } else {
        "—".into()
    }
}

fn main() {
    println!("# Document 22 — Routing Simulation Results\n");
    println!(
        "**Generated by** `cargo run -p vl-sim --release` · seeds {SEEDS:?} (mean of 5 runs per cell)\n"
    );
    println!(
        "> **These are simulation results, not Bluetooth measurements.** Mobility, encounter durations, goodput (20 kB/s assumed) and participation rates are modelling assumptions. Every node runs the production `vl-routing` engine with wire-encoded link messages; protocol caps (per-session 32 envelopes / 64 KiB, per-tag 8, carry cap 10 MiB) apply to every algorithm. Best-effort nodes model iPhones in background that complete a session in only a share of encounters.\n"
    );
    println!(
        "Columns: delivery = share of messages reaching the recipient; ack = share whose sender obtained delivery proof (receipt or vaccine); p50/p90 = delivery latency in minutes; transfers/delivery = envelope transmissions (data + receipts) per delivered message; peak store = largest per-node store in KiB.\n"
    );
    for s in standard_scenarios() {
        println!("## {}\n", s.name);
        println!(
            "| algorithm | delivery | ack | p50 min | p90 min | ack p50 min | transfers/delivery | peak store KiB |"
        );
        println!("|---|---|---|---|---|---|---|---|");
        for (name, alg) in algorithms() {
            let runs: Vec<Metrics> = SEEDS.iter().map(|seed| run(&s, alg, *seed)).collect();
            println!(
                "| {name} | {} | {} | {} | {} | {} | {} | {} |",
                fmt(mean(&runs, Metrics::delivery_ratio), 2),
                fmt(mean(&runs, Metrics::ack_ratio), 2),
                fmt(mean(&runs, |m| m.latency_p50_min), 0),
                fmt(mean(&runs, |m| m.latency_p90_min), 0),
                fmt(mean(&runs, |m| m.ack_latency_p50_min), 0),
                fmt(mean(&runs, |m| m.transfers_per_delivery), 1),
                fmt(mean(&runs, |m| m.peak_store_bytes as f64 / 1024.0), 0),
            );
        }
        println!();
    }
}
